#!/usr/bin/env python3
"""Write the env file that keeps Brain's previous flag defaults.

Brain's defaults live in code, so a new release can start new background
work without any configuration change. This script compares two dumps of
Brain's config catalog, `{"KEY": {"default": "0", "boolean": true}}`:
the one of the release Manifold ran before (baseline) and the one being
built (current). It pins every changed default to its previous value and
every new boolean flag that is on to 0. Keys listed in the adopt file keep
the new upstream default.
"""

import argparse
import json
import pathlib
import sys

ON = {"1", "true"}
HEADER = """# Generated by scripts/brain-flags.py; do not edit.
# Brain's previous defaults for keys whose default changed, and 0 for new
# boolean flags that upstream ships switched on. Environment values win.
"""


def render_value(value):
    if any(c in value for c in " \t#\"'"):
        quote = "'" if '"' in value else '"'
        return f"{quote}{value}{quote}"
    return value


def pins(baseline, current, adopted):
    result, unpinnable = {}, []
    for key, now in current.items():
        if key in adopted:
            continue
        before = baseline.get(key)
        if before is None:
            if now["boolean"] and str(now["default"]).lower() in ON:
                result[key] = "0"
        elif before["default"] != now["default"]:
            if before["default"] is None:
                unpinnable.append(key)
            else:
                result[key] = str(before["default"])
    return result, sorted(unpinnable)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--baseline", required=True, type=pathlib.Path)
    parser.add_argument("--current", required=True, type=pathlib.Path)
    parser.add_argument("--adopt", required=True, type=pathlib.Path)
    parser.add_argument("--out", required=True, type=pathlib.Path)
    parser.add_argument("--check", action="store_true", help="fail if --out is stale")
    args = parser.parse_args()

    adopted = set()
    for line in args.adopt.read_text().splitlines():
        key = line.split("#", 1)[0].strip()
        if key:
            adopted.add(key)
    result, unpinnable = pins(
        json.loads(args.baseline.read_text()), json.loads(args.current.read_text()), adopted
    )
    if unpinnable:
        print(
            "brain-flags: the default changed but the baseline has none; decide in "
            f"{args.adopt}: {', '.join(unpinnable)}",
            file=sys.stderr,
        )
        return 1
    text = HEADER + "".join(f"{k}={render_value(v)}\n" for k, v in sorted(result.items()))
    if args.check:
        if not args.out.exists() or args.out.read_text() != text:
            print(f"brain-flags: {args.out} is stale; regenerate it", file=sys.stderr)
            return 1
        return 0
    args.out.write_text(text)
    print(f"brain-flags: wrote {len(result)} pins to {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
